"""Generate rtl/fpga/arr_emu_lut.svh: the device statistics the FPGA array emulator draws from (9 October 2026).

Two kinds of numbers, from two sources:
  - Pulse thresholds (the amplitude step 0..20 at which a set or a reset pulse succeeds): the device model's
    programming Monte Carlo, results/program_mc.json (rows of "reset_pulses" / "set_pulses"; a failed reset never
    succeeds). Bank 0: tt 1x, bank 1: tt 2x, bank 2: ss 2x. 100 devices each, padded to 128 by repeating.
  - Read levels after a successful pulse: the published IHP statistics (array/tile.py IHP_STATS, Perez et al. 2021):
    HRS 2.85 +/- 1.85 uA, LRS3 43.59 +/- 1.55 uA, sigma x1 / x2 / x3 for banks 0 / 1 / 2, drawn on the FPGA as
    mean + sigma * q, q from a 256-entry table of standard-normal quantiles (in 1/16).
Codes: 0.25 uA per LSB (read at 0.2 V), 8 bits. References: read 25.0 uA (100), set verify 42 uA (168), reset verify 6 uA (24).
"""
import json
from pathlib import Path
from statistics import NormalDist

ROOT = Path(__file__).resolve().parents[1]
d = json.loads((ROOT / "results" / "program_mc.json").read_text())["runs"]
BANKS = ("tt 1x", "tt 2x", "ss 2x")
LSB = 0.25
HRS, LRS = (2.85, 1.85), (43.59, 1.55)
SCALE = (1, 2, 3)

lines = ["// generated by tools/make_devlut.py from results/program_mc.json and the published IHP statistics; do not edit", ""]
lines.append("// read-only tables as functions (constant logic). An initial block filling a memory was tried first; Yosys'")
lines.append("// slang front end dropped its contents, which the gate-level run showed (all thresholds read as 0).")
lines.append("function automatic logic [9:0] thr_lut(input logic [8:0] a); // a = {bank, personality}; {reset step, set step}, 31 = never")
lines.append("    case (a)")
for b_, name in enumerate(BANKS):
    devs = d[name]["devices"]
    for i in range(128):
        x = devs[i % len(devs)]
        r = x["reset_pulses"] - 1 if x["reset_ok"] else 31
        s_ = x["set_pulses"] - 1 if x["set_ok"] else 31
        lines.append(f"        9'd{b_ * 128 + i}: thr_lut = {{5'd{r}, 5'd{s_}}};")
lines.append("        default: thr_lut = {5'd31, 5'd31};")
lines.append("    endcase")
lines.append("endfunction")
lines.append("function automatic logic [7:0] q_lut(input logic [7:0] u); // standard-normal quantile of (u + 0.5) / 256, in 1/16")
lines.append("    case (u)")
for u in range(256):
    q = int(round(NormalDist().inv_cdf((u + 0.5) / 256) * 16))
    lines.append(f"        8'd{u}: q_lut = 8'h{q & 0xff:02x};   // {q}")
lines.append("    endcase")
lines.append("endfunction")
lines.append("")
for nm, (mu, sg) in (("HRS", HRS), ("LRS", LRS)):
    lines.append(f"// {nm}_MEAN = {int(round(mu / LSB))}   ({mu} uA; used in lev_lut)")
    for b, k in enumerate(SCALE):
        lines.append(f"// {nm}_SIG{b} = {int(round(sg * k / LSB * 16))}   (sigma x{k} in 1/16 LSB; used in lev_lut)")
# Level drawn by a successful pulse, as a table (10 October 2026): lev_lut({hi, bank, u}) =
#   MEAN + floor(SIG * q / 256), clamped to 0..255, with q = q_lut(u). The emulator used to compute this with a
#   multiplier; a table needs none (the board's signed multiplier gave wrong products, and the unsigned 9 x 9 one that
#   replaced it could not be placed by nextpnr). Bank 3 behaves as bank 2, as in the former draw().
mean = {nm: int(round(mu / LSB)) for nm, (mu, sg) in (("HRS", HRS), ("LRS", LRS))}
sigs = {nm: [int(round(sg * k / LSB * 16)) for k in SCALE] for nm, (mu, sg) in (("HRS", HRS), ("LRS", LRS))}
lines.append("function automatic logic [7:0] lev_lut(input logic [10:0] a); // level after a pulse: {hi, bank, u}")
lines.append("    case (a)")
for hi in (0, 1):
    nm = "LRS" if hi else "HRS"
    for bank in range(4):
        sg = sigs[nm][min(bank, 2)]
        for u in range(256):
            q = int(round(NormalDist().inv_cdf((u + 0.5) / 256) * 16))
            v = max(0, min(255, mean[nm] + (sg * q) // 256))
            lines.append(f"        11'd{(hi << 10) | (bank << 8) | u}: lev_lut = 8'd{v};")
lines.append("    endcase")
lines.append("endfunction")
step = (LRS[0] - HRS[0]) / LSB
assert int(round(65536 / step)) % 2 == 0, "arr_emu.sv takes STEP_RECIP / 2 off exactly: STEP_RECIP must be even"
lines.append(f"localparam int STEP_RECIP = {int(round(65536 / step))};   // 65536 / ((LRS - HRS mean) / LSB) = 65536 / {step:.2f}")
(ROOT / "rtl" / "fpga").mkdir(parents=True, exist_ok=True)
(ROOT / "rtl" / "fpga" / "arr_emu_lut.svh").write_text("\n".join(lines) + "\n")
print("written", len(lines), "lines")
